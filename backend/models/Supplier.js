const mongoose = require('mongoose');

// ============================================================
// SUPPLIER SCHEMA
// ============================================================

const supplierSchema = new mongoose.Schema(
  {
    // --------------------------------------------------------
    // SUPPLIER NAME
    // --------------------------------------------------------
    name: {
      type: String,
      required: true,
      trim: true,
    },

    // --------------------------------------------------------
    // CONTACT NUMBER
    // --------------------------------------------------------
    contact: {
      type: String,
      required: true,
      trim: true,
    },

    // --------------------------------------------------------
    // EMAIL
    // --------------------------------------------------------
    email: {
      type: String,
      trim: true,
      default: '',
    },

    // --------------------------------------------------------
    // ADDRESS
    // --------------------------------------------------------
    address: {
      type: String,
      trim: true,
      default: '',
    },

    // --------------------------------------------------------
    // STATUS
    // --------------------------------------------------------
    status: {
      type: String,
      enum: ['active', 'inactive'],
      default: 'active',
    },

    // --------------------------------------------------------
    // NUMBER OF MEDICINES
    // --------------------------------------------------------
    medicines: {
      type: Number,
      default: 0,
      min: 0,
    },

    // --------------------------------------------------------
    // LAST ORDER DATE
    // --------------------------------------------------------
    lastOrder: {
      type: Date,
      default: null,
    },
  },
  {
    timestamps: true,
  }
);

// ============================================================
// SUPPLIER MODEL
// ============================================================

module.exports =
  mongoose.models.Supplier ||
  mongoose.model('Supplier', supplierSchema);